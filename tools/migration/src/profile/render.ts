/**
 * Renders a `Profile` as the markdown committed to `docs/migration/profile-<date>.md`.
 * Only counts, identifiers and the filtered status codes from the profile are printed.
 */
import { compareIds, HELD_BACK_ID } from "./collect";
import type { ColumnProfile, Profile, TableProfile } from "./types";

const fmt = (value: number): string => value.toLocaleString("en-US");

function table(header: readonly string[], rows: readonly (readonly string[])[]): string {
  const line = (cells: readonly string[]) => `| ${cells.join(" | ")} |`;
  return [line(header), line(header.map(() => "---")), ...rows.map(line)].join("\n");
}

const code = (identifier: string): string => `\`${identifier.replaceAll("`", "'")}\``;

function columnsWhere(
  profile: Profile,
  keep: (column: ColumnProfile) => boolean,
): { table: TableProfile; column: ColumnProfile }[] {
  return profile.tables.flatMap((t) =>
    t.columns.filter(keep).map((column) => ({ table: t, column })),
  );
}

export function renderProfile(profile: Profile): string {
  const out: string[] = [];
  const documentedFound = profile.tables.filter((t) => t.documented).length;
  out.push(`# Legacy data profile, ${profile.date}`);
  out.push("");
  out.push(
    "> **Counts only.** This report holds no names, phone numbers, addresses, passwords or other " +
      "row values. Status codes are listed only when they are short codes used by at least 5 rows " +
      "and do not match any personal value; everything else is counted, not shown. The file was " +
      "checked for personal data automatically before it was written (`tools/migration`, " +
      "`src/pii/scan.ts`). Generated by `pnpm --filter @cb/migration legacy:profile`.",
  );
  out.push("");
  out.push(
    table(
      ["", ""],
      [
        ["Generated (UTC)", profile.generatedAt],
        [
          "Copy run",
          profile.copyRun
            ? `#${profile.copyRun.id} from ${code(profile.copyRun.sourceLabel)}, finished ${profile.copyRun.finishedAt ?? "?"}`
            : "unknown",
        ],
        ["Tables copied", fmt(profile.tables.length)],
        [
          "Documented tables found",
          `${documentedFound} of ${documentedFound + profile.missingDocumentedTables.length}` +
            (profile.missingDocumentedTables.length > 0
              ? ` (missing: ${profile.missingDocumentedTables.map(code).join(", ")})`
              : ""),
        ],
      ],
    ),
  );

  out.push("", "## 1. Tables", "");
  out.push(
    table(
      ["Table", "Documented", "Rows", "Baseline (PRD App. A)", "Difference", "Columns"],
      profile.tables.map((t) => [
        code(t.name),
        t.documented ? "yes" : "no",
        fmt(t.rows),
        t.baseline === null ? "" : fmt(t.baseline),
        t.baseline === null ? "" : fmt(t.rows - t.baseline),
        fmt(t.columns.length),
      ]),
    ),
  );

  out.push("", "## 2. Rows per operator", "");
  out.push(renderOperators(profile));

  out.push("", "## 3. References: null, zero and orphan", "");
  out.push(
    "An orphan points at a parent row that does not exist. Zero means the reference is `0` or " +
      "empty, which legacy code often used for “none”.",
    "",
  );
  out.push(
    table(
      ["Check", "Column → key", "Rows", "Null", "Zero", "Orphan"],
      profile.relations.map((r) =>
        r.status.checked
          ? [
              r.name,
              `${code(r.status.column)} → ${code(r.status.parentKey ?? "")}`,
              fmt(r.rows),
              fmt(r.nulls),
              fmt(r.zero),
              fmt(r.orphans),
            ]
          : [r.name, `not checked: ${r.status.reason}`, "", "", "", ""],
      ),
    ),
  );

  out.push("", "## 4. Duplicates", "");
  out.push(
    "Values compared after trimming spaces and ignoring case. Groups = values used more than once; " +
      "rows = rows sharing such a value.",
    "",
  );
  out.push(
    table(
      ["Check", "Column", "Groups", "Rows in groups"],
      profile.duplicates.map((d) =>
        d.status.checked
          ? [d.name, code(d.status.column), fmt(d.groups), fmt(d.rows)]
          : [d.name, `not checked: ${d.status.reason}`, "", ""],
      ),
    ),
  );
  const perOperator = profile.duplicates.flatMap((d) =>
    d.byOperator.map((b) => [d.name, b.operator, fmt(b.groups), fmt(b.rows)]),
  );
  if (perOperator.length > 0) {
    out.push("", "Per operator:", "");
    out.push(table(["Check", "Operator", "Groups", "Rows in groups"], perOperator));
  }

  out.push("", "## 5. Dates", "");
  out.push(
    "Dates are copied as the text MariaDB printed. Zero = `0000-00-00`; invalid = neither zero " +
      "nor a real date (`2019-00-10`, `2021-02-30`). Earliest and latest count valid values only.",
    "",
  );
  const dates = columnsWhere(profile, (c) => c.dates !== null);
  out.push(
    dates.length === 0
      ? "No date columns."
      : table(
          ["Column", "Type", "Null", "Blank", "Zero date", "Invalid", "Earliest", "Latest"],
          dates.map(({ table: t, column: c }) => [
            code(`${t.name}.${c.name}`),
            code(c.sourceType),
            fmt(c.nulls),
            fmt(c.blank ?? 0),
            fmt(c.dates?.zero ?? 0),
            fmt(c.dates?.invalid ?? 0),
            c.dates?.min ?? "",
            c.dates?.max ?? "",
          ]),
        ),
  );

  out.push("", "## 6. Numbers: floats, decimals and money", "");
  out.push(
    "Float and decimal columns, plus integer columns whose names say money. “More than 2 " +
      "decimals” is finer than a paisa if the unit is rupees. “Whole hundreds” " +
      "(non-zero multiples of 100) is evidence for the money unit (rupees vs paise).",
    "",
  );
  const numbers = columnsWhere(profile, (c) => c.numbers !== null);
  out.push(
    numbers.length === 0
      ? "No numeric columns to check."
      : table(
          [
            "Column",
            "Type",
            "Null",
            "Negative",
            "Zero",
            "Fractional",
            "More than 2 decimals",
            "Whole hundreds",
          ],
          numbers.map(({ table: t, column: c }) => [
            code(`${t.name}.${c.name}`),
            code(c.sourceType),
            fmt(c.nulls),
            fmt(c.numbers?.negative ?? 0),
            fmt(c.numbers?.zero ?? 0),
            fmt(c.numbers?.fractional ?? 0),
            fmt(c.numbers?.subPaisa ?? 0),
            c.numbers?.wholeHundreds === null || c.numbers?.wholeHundreds === undefined
              ? ""
              : fmt(c.numbers.wholeHundreds),
          ]),
        ),
  );

  out.push("", "## 7. Status values", "");
  out.push(
    "Status-like columns only (flags such as `isReceipt`, and `status`/`type`/`mode` columns). " +
      "A value is shown only when at least 5 rows use it, it is a short code, and it matches no " +
      "name, phone, address, login or password in the data. Other values are counted as held back.",
    "",
  );
  const statuses = columnsWhere(profile, (c) => c.values !== null);
  if (statuses.length === 0) out.push("No status-like columns.");
  for (const { table: t, column: c } of statuses) {
    const values = c.values;
    if (!values) continue;
    out.push(`### ${code(`${t.name}.${c.name}`)} (${code(c.sourceType)})`, "");
    if (values.tooMany) {
      out.push(
        `${fmt(c.distinct)} distinct values: too many for a status column, so none are listed.`,
        "",
      );
      continue;
    }
    const rows = values.shown.map((v) => [code(v.value), fmt(v.rows)]);
    if (c.nulls > 0) rows.push(["(null)", fmt(c.nulls)]);
    if (values.suppressedValues > 0) {
      rows.push([`(${fmt(values.suppressedValues)} held back)`, fmt(values.suppressedRows)]);
    }
    out.push(rows.length === 0 ? "No rows." : table(["Value", "Rows"], rows), "");
  }

  out.push("## 8. Columns", "");
  out.push(
    "Class: `sensitive` = personal or secret data by column name (values never reported); " +
      "`status` = values listed in section 7; `money` = numbers checked in section 6.",
  );
  for (const t of profile.tables) {
    out.push("", `### ${code(t.name)} (${fmt(t.rows)} rows)`, "");
    out.push(
      table(
        ["Column", "Type", "Key", "Class", "Null", "Blank", "Distinct"],
        t.columns.map((c) => [
          code(c.name),
          code(c.sourceType),
          c.primaryKey ? "PK" : "",
          c.class === "enum" ? "status" : c.class === "other" ? "" : c.class,
          fmt(c.nulls),
          c.blank === null ? "" : fmt(c.blank),
          fmt(c.distinct),
        ]),
      ),
    );
    const nul = t.columns.filter((c) => c.nulBytesRemoved > 0);
    if (nul.length > 0) {
      out.push(
        "",
        `NUL characters removed during the copy: ${nul
          .map((c) => `${code(c.name)} ${fmt(c.nulBytesRemoved)} rows`)
          .join(", ")}.`,
      );
    }
  }

  out.push("", "## Notes", "");
  out.push(
    "- Column names used by sections 2 to 4 are matched from candidate lists in " +
      "`tools/migration/src/config.ts`. A “not checked” line names the candidates " +
      "tried: add the real column name there and run the profile again.",
    "- Operator ids are the legacy `op_id` values. Display names are never shown (two operators " +
      "can share a name, PRD §14).",
    "- Next step: the mapping document `docs/migration/mapping.md` (T-091).",
    "",
  );
  return out.join("\n");
}

function renderOperators(profile: Profile): string {
  const breakdown = profile.operators;
  if (!breakdown) {
    return "Not checked: no operator table with a key column (see `OPERATOR_KEY_CANDIDATES`).";
  }
  if (breakdown.tables.length === 0) return "No table has an operator column.";
  const known = new Set(breakdown.operatorIds);
  const ids = new Set<string>(breakdown.operatorIds);
  for (const t of breakdown.tables) for (const id of Object.keys(t.byOperator)) ids.add(id);
  const sorted = [...ids].sort(compareIds);
  const header = ["Operator", ...breakdown.tables.map((t) => `${code(t.table)}.${code(t.column)}`)];
  const rows = sorted.map((id) => [
    known.has(id) || id === HELD_BACK_ID ? id : `${id} (not in operator table)`,
    ...breakdown.tables.map((t) => fmt(t.byOperator[id] ?? 0)),
  ]);
  rows.push(["(null)", ...breakdown.tables.map((t) => fmt(t.nullOperator))]);
  rows.push(["Total rows", ...breakdown.tables.map((t) => fmt(t.total))]);
  rows.push(["Sum of groups", ...breakdown.tables.map((t) => fmt(t.groupSum))]);
  rows.push(["Not a known operator", ...breakdown.tables.map((t) => fmt(t.unknownOperator))]);
  const mismatched = breakdown.tables.filter((t) => t.total !== t.groupSum);
  return [
    `${fmt(breakdown.operatorIds.length)} operator ids in the operator table.`,
    "",
    table(header, rows),
    "",
    mismatched.length === 0
      ? "Per-operator groups add up to the table totals in every table."
      : `Per-operator groups do not add up to the total in: ${mismatched.map((t) => code(t.table)).join(", ")}.`,
  ].join("\n");
}
