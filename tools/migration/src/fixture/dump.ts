import { quoteMysqlIdent } from "../source/mariadb";
import type { MemoryTable } from "../source/memory";
import type { LegacyValue } from "../source/types";

const STRING_ESCAPES: Readonly<Record<string, string>> = {
  "\0": "\\0",
  "\n": "\\n",
  "\r": "\\r",
  "\x1a": "\\Z",
  "'": "\\'",
  '"': '\\"',
  "\\": "\\\\",
};

/** Escapes a value for a MySQL/MariaDB INSERT, the way mysqldump does. */
export function mysqlLiteral(value: LegacyValue): string {
  if (value === null || value === undefined) return "NULL";
  if (typeof value === "number") {
    if (!Number.isFinite(value)) throw new TypeError("non-finite number in fixture");
    return Object.is(value, -0) ? "0" : String(value);
  }
  if (typeof value === "bigint") return value.toString();
  if (Buffer.isBuffer(value)) return value.length === 0 ? "''" : `0x${value.toString("hex")}`;
  const escaped = Array.from(value, (ch) => STRING_ESCAPES[ch] ?? ch).join("");
  return `'${escaped}'`;
}

/**
 * Writes the fixture as a mysqldump-style SQL script (DROP/CREATE TABLE + multi-row INSERTs),
 * so `restore.sh` loads it exactly like a real dump. Zero dates need a non-strict SQL mode,
 * which the script sets for its own session (as real dumps of this database must).
 */
export function* toMysqlDump(
  tables: readonly MemoryTable[],
  options: { rowsPerInsert?: number } = {},
): Generator<string> {
  const rowsPerInsert = options.rowsPerInsert ?? 500;
  yield "-- Synthetic legacy fixture: FAKE data generated by `pnpm --filter @cb/migration legacy:fixture`.\n";
  yield "-- Not a real dump. Column names other than the documented ones are invented.\n";
  yield "SET NAMES utf8mb4;\n";
  yield "SET SESSION sql_mode = 'NO_ENGINE_SUBSTITUTION';\n";
  yield "SET FOREIGN_KEY_CHECKS = 0;\n\n";
  for (const table of tables) {
    const name = quoteMysqlIdent(table.name);
    const definitions = table.columns.map(
      (c) =>
        `  ${quoteMysqlIdent(c.name)} ${c.columnType}${c.nullable ? " DEFAULT NULL" : " NOT NULL"}`,
    );
    const primary = table.columns.filter((c) => c.primaryKey).map((c) => quoteMysqlIdent(c.name));
    if (primary.length > 0) definitions.push(`  PRIMARY KEY (${primary.join(", ")})`);
    yield `DROP TABLE IF EXISTS ${name};\n`;
    yield `CREATE TABLE ${name} (\n${definitions.join(",\n")}\n) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;\n`;
    const columnList = table.columns.map((c) => quoteMysqlIdent(c.name)).join(", ");
    for (let i = 0; i < table.rows.length; i += rowsPerInsert) {
      const tuples = table.rows
        .slice(i, i + rowsPerInsert)
        .map((row) => `(${row.map((v) => mysqlLiteral(v)).join(",")})`);
      yield `INSERT INTO ${name} (${columnList}) VALUES ${tuples.join(",")};\n`;
    }
    yield "\n";
  }
}
