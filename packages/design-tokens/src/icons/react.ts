/**
 * Lucide icons → `packages/ui/src/icons/icons.generated.ts`: plain data (element tag + attributes per
 * icon) that `@cb/ui`'s `<Icon name="cash" />` renders as inline SVG. No runtime icon library: the web
 * draws the exact same Lucide elements the Android vectors are converted from.
 */
import { type IconNode, LUCIDE_SVG, SUPPORTED_ELEMENTS } from "./svg";

export const REACT_ICONS_PATH = "packages/ui/src/icons/icons.generated.ts";

export type ReactIcon = { name: string; lucide: string; node: IconNode };

/** Only presentation attributes React accepts as written (no `stroke-width`-style names). */
const REACT_ATTRIBUTE = /^[a-z][a-zA-Z0-9]*$/;

function renderElement([tag, attributes]: IconNode[number]): string {
  if (!SUPPORTED_ELEMENTS.includes(tag)) throw new Error(`unsupported element <${tag}>`);
  const pairs = Object.entries(attributes).map(([key, value]) => {
    if (!REACT_ATTRIBUTE.test(key)) throw new Error(`<${tag}>: unsupported attribute "${key}"`);
    return `${key}: ${JSON.stringify(value)}`;
  });
  return `["${tag}", { ${pairs.join(", ")} }]`;
}

/** Renders the TypeScript module with every icon's SVG elements. */
export function renderReactIcons(icons: readonly ReactIcon[], version: string): string {
  const body = icons.flatMap(({ name, lucide, node }) => [
    `  // Lucide "${lucide}"`,
    `  ${JSON.stringify(name)}: [`,
    ...node.map((element) => `    ${renderElement(element)},`),
    "  ],",
  ]);
  return [
    "// GENERATED by packages/design-tokens/scripts/icons.ts from packages/design-tokens/icons.json.",
    "// Do not edit: change icons.json and run `pnpm icons:build`.",
    `// Icon data: lucide-static ${version}, ISC licence (see LICENSE-lucide.txt next to this file).`,
    "",
    "/** The `<svg>` attributes every icon is drawn with (Lucide's 24×24 outline style). */",
    "export const ICON_SVG_ATTRIBUTES = {",
    `  viewBox: "${LUCIDE_SVG.viewBox}",`,
    '  fill: "none",',
    '  stroke: "currentColor",',
    `  strokeWidth: ${LUCIDE_SVG.strokeWidth},`,
    `  strokeLinecap: "${LUCIDE_SVG.strokeLinecap}",`,
    `  strokeLinejoin: "${LUCIDE_SVG.strokeLinejoin}",`,
    "} as const;",
    "",
    "/** Semantic icon name → the SVG elements to draw, in order. */",
    "export const ICON_NODES = {",
    ...body,
    "} as const;",
    "",
    "/** A semantic icon name from icons.json. */",
    "export type IconName = keyof typeof ICON_NODES;",
    "",
  ].join("\n");
}
