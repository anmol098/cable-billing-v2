/**
 * Lucide icon → Android VectorDrawable XML (`ic_cb_<name>.xml`).
 *
 * Tinting: every path is drawn in opaque white and the vector carries
 * `android:tint="?android:attr/colorControlNormal"`, the same pattern as Android Studio's Material
 * icons. Compose `Icon(painterResource(R.drawable.ic_cb_cash), contentDescription, tint = …)` and
 * `ImageView` tints replace the colour (SrcIn), so call sites pick a token colour
 * (`Tokens.Color.Cash`, `LocalContentColor`); with no tint the theme's control colour is used.
 * No hex colour appears in the files.
 */
import { elementToPath, type IconNode, LUCIDE_SVG } from "./svg";

export const ANDROID_DRAWABLE_DIR = "apps/android/core/designsystem/src/main/res/drawable";

/** Colour the paths are drawn in before tinting. */
const PAINT = "@android:color/white";
const TINT = "?android:attr/colorControlNormal";

export type IconSource = {
  /** Semantic name from icons.json (`cash`). */
  name: string;
  /** Lucide icon name (`banknote`). */
  lucide: string;
  /** lucide-static version the data came from. */
  version: string;
};

/** XML comments may not contain `--`; names never do (validated), but be safe. */
const comment = (text: string) => `<!-- ${text.replaceAll("--", "- -")} -->`;

/** Renders the VectorDrawable XML for one icon. */
export function renderVectorDrawable(source: IconSource, node: IconNode): string {
  if (node.length === 0) throw new Error(`icon "${source.name}" has no elements`);
  const { size } = LUCIDE_SVG;
  const paths = node.map((element) => {
    const { pathData, filled } = elementToPath(element);
    return [
      "    <path",
      `        android:pathData="${pathData}"`,
      ...(filled ? [`        android:fillColor="${PAINT}"`] : []),
      `        android:strokeColor="${PAINT}"`,
      `        android:strokeWidth="${LUCIDE_SVG.strokeWidth}"`,
      `        android:strokeLineCap="${LUCIDE_SVG.strokeLinecap}"`,
      `        android:strokeLineJoin="${LUCIDE_SVG.strokeLinejoin}" />`,
    ].join("\n");
  });
  return [
    '<?xml version="1.0" encoding="utf-8"?>',
    comment(
      "GENERATED by packages/design-tokens/scripts/icons.ts from packages/design-tokens/icons.json. Do not edit.",
    ),
    comment(
      `"${source.name}" = Lucide "${source.lucide}" (lucide-static ${source.version}, ISC licence; see packages/ui/src/icons/LICENSE-lucide.txt).`,
    ),
    '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
    `    android:width="${size}dp"`,
    `    android:height="${size}dp"`,
    `    android:viewportWidth="${size}"`,
    `    android:viewportHeight="${size}"`,
    `    android:tint="${TINT}">`,
    ...paths,
    "</vector>",
    "",
  ].join("\n");
}
