import { describe, expect, it } from "vitest";
import { renderVectorDrawable } from "./android";
import { loadLucide } from "./fs";
import type { IconNode } from "./svg";

describe("renderVectorDrawable", () => {
  it("snapshot: cash (Lucide banknote: rect with rx, circle, dot path)", () => {
    const lucide = loadLucide();
    const node = lucide.nodes.banknote;
    if (!node) throw new Error("banknote missing from lucide-static");
    expect(
      renderVectorDrawable({ name: "cash", lucide: "banknote", version: "1.55.0" }, node),
    ).toMatchInlineSnapshot(`
        "<?xml version="1.0" encoding="utf-8"?>
        <!-- GENERATED by packages/design-tokens/scripts/icons.ts from packages/design-tokens/icons.json. Do not edit. -->
        <!-- "cash" = Lucide "banknote" (lucide-static 1.55.0, ISC licence; see packages/ui/src/icons/LICENSE-lucide.txt). -->
        <vector xmlns:android="http://schemas.android.com/apk/res/android"
            android:width="24dp"
            android:height="24dp"
            android:viewportWidth="24"
            android:viewportHeight="24"
            android:tint="?android:attr/colorControlNormal">
            <path
                android:pathData="M4 6 H20 A2 2 0 0 1 22 8 V16 A2 2 0 0 1 20 18 H4 A2 2 0 0 1 2 16 V8 A2 2 0 0 1 4 6 Z"
                android:strokeColor="@android:color/white"
                android:strokeWidth="2"
                android:strokeLineCap="round"
                android:strokeLineJoin="round" />
            <path
                android:pathData="M10 12 a2 2 0 1 0 4 0 a2 2 0 1 0 -4 0 Z"
                android:strokeColor="@android:color/white"
                android:strokeWidth="2"
                android:strokeLineCap="round"
                android:strokeLineJoin="round" />
            <path
                android:pathData="M6 12 h0.01 M18 12 h0.01"
                android:strokeColor="@android:color/white"
                android:strokeWidth="2"
                android:strokeLineCap="round"
                android:strokeLineJoin="round" />
        </vector>
        "
      `);
  });

  it("fills elements Lucide fills, and never writes a hex colour", () => {
    const node: IconNode = [
      ["circle", { cx: "7.5", cy: "7.5", r: ".5", fill: "currentColor" }],
      ["line", { x1: "1", y1: "1", x2: "2", y2: "2" }],
    ];
    const xml = renderVectorDrawable({ name: "dot", lucide: "x", version: "0" }, node);
    expect(xml.match(/android:fillColor="@android:color\/white"/g)).toHaveLength(1);
    expect(xml.match(/android:strokeColor=/g)).toHaveLength(2);
    expect(xml).not.toMatch(/#[0-9A-Fa-f]{6,8}/);
  });

  it("rejects an empty icon", () => {
    expect(() => renderVectorDrawable({ name: "x", lucide: "x", version: "0" }, [])).toThrow(
      "no elements",
    );
  });
});
