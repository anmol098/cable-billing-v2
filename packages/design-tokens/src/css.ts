import type { Tokens } from "./schema";
import { cssFontFamily, cssFontFeatures, hexToCss, kebabCase, pxToCss, pxToRem } from "./transform";

/**
 * Tailwind namespaces cleared before the tokens are added, so the default palette, type scale,
 * radii, fonts and every kind of shadow do not exist as utilities. Only tokens remain.
 */
export const RESET_NAMESPACES = [
  "color",
  "font",
  "font-weight",
  "text",
  "radius",
  "shadow",
  "inset-shadow",
  "drop-shadow",
  "text-shadow",
] as const;

/** Sides that get their own border-width utility, e.g. `border-b-hairline`. */
const BORDER_SIDES: readonly (readonly [side: string, property: string])[] = [
  ["", "border-width"],
  ["x", "border-inline-width"],
  ["y", "border-block-width"],
  ["t", "border-top-width"],
  ["r", "border-right-width"],
  ["b", "border-bottom-width"],
  ["l", "border-left-width"],
];

/** Renders `packages/ui/src/theme.css`: a Tailwind v4 `@theme` holding every web token. */
export function renderThemeCss(tokens: Tokens): string {
  const lines: string[] = [];
  const v = (name: string, value: string) => lines.push(`  --${name}: ${value};`);
  const comment = (text: string) => lines.push("", `  /* ${text} */`);

  lines.push(
    "/*",
    " * GENERATED by @cb/design-tokens (packages/design-tokens/scripts/build.ts). Do not edit.",
    " * Change packages/design-tokens/tokens.json, then run `pnpm tokens:build`.",
    " */",
    '@import "tailwindcss";',
    "",
    "/* `static`: every token is always a CSS variable, e.g. var(--color-cash), even if unused. */",
    "@theme static {",
    "  /* Clear Tailwind's defaults: only tokens exist as utilities. */",
  );
  for (const namespace of RESET_NAMESPACES) v(`${namespace}-*`, "initial");

  comment("color");
  for (const [name, token] of Object.entries(tokens.color)) {
    v(`color-${kebabCase(name)}`, hexToCss(token.value));
  }
  comment("semantic: fixed meanings (cash, UPI, pending, …), identical on Android");
  for (const [name, token] of Object.entries(tokens.semantic)) {
    v(`color-${kebabCase(name)}`, hexToCss(token.value));
  }

  comment("font");
  for (const [name, token] of Object.entries(tokens.font.family)) {
    v(`font-${kebabCase(name)}`, cssFontFamily(token.value));
    if (token.features?.length) {
      v(`font-${kebabCase(name)}--font-feature-settings`, cssFontFeatures(token.features));
    }
  }
  for (const [name, token] of Object.entries(tokens.font.weight)) {
    v(`font-weight-${kebabCase(name)}`, String(token.value));
  }

  comment("type: web scale");
  for (const [name, px] of Object.entries(tokens.type.web)) {
    v(`text-${kebabCase(name)}`, pxToRem(px));
  }

  comment("radius");
  for (const [name, px] of Object.entries(tokens.radius)) {
    v(`radius-${kebabCase(name)}`, pxToRem(px));
  }

  comment("space: every spacing utility (p-4, gap-2, …) is a multiple of this");
  v("spacing", pxToRem(tokens.space.base));

  comment("size: h-touch-min, min-h-primary-button, …");
  for (const [name, size] of Object.entries(tokens.size)) {
    v(`spacing-${kebabCase(name)}`, pxToRem(size.web));
  }

  lines.push(
    "",
    "  /* elevation: none on the web; shadows are cleared above (hyper-minimal). */",
    "}",
    "",
    "/* Tailwind v4 has no border-width theme namespace, so border tokens are utilities. */",
  );
  for (const [name, px] of Object.entries(tokens.border)) {
    for (const [side, property] of BORDER_SIDES) {
      const utility = side ? `border-${side}-${kebabCase(name)}` : `border-${kebabCase(name)}`;
      lines.push(`@utility ${utility} { ${property}: ${pxToCss(px)}; }`);
    }
  }

  return `${lines.join("\n")}\n`;
}
