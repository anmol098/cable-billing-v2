import type { Tokens } from "./schema";
import {
  composeFontFeatures,
  dp,
  hexToComposeColor,
  kotlinString,
  pascalCase,
  sp,
} from "./transform";

export const KOTLIN_PACKAGE = "com.cablebilling.designsystem.generated";

/** Compose's `Color` is imported under this alias because `Tokens.Color` shadows the name. */
const COLOR_ALIAS = "ComposeColor";
const INDENT = "    ";

type Member = { name: string; value: string; comment?: string };

function object(name: string, members: readonly Member[]): string[] {
  const seen = new Set<string>();
  const body: string[] = [];
  for (const member of members) {
    if (seen.has(member.name)) {
      throw new Error(`Tokens.${name}.${member.name} would be generated twice`);
    }
    seen.add(member.name);
    if (member.comment) body.push(`${INDENT}${INDENT}// ${member.comment}`);
    body.push(`${INDENT}${INDENT}val ${member.name} = ${member.value}`);
  }
  return [`${INDENT}object ${name} {`, ...body, `${INDENT}}`];
}

const lengths = (entries: Record<string, number>, unit: (value: number) => string): Member[] =>
  Object.entries(entries).map(([name, value]) => ({ name: pascalCase(name), value: unit(value) }));

/**
 * Renders `Tokens.kt` for the Android `core/designsystem` module. Android values only:
 * the `android` type scale and sizes, dp for lengths, sp for text.
 */
export function renderTokensKt(tokens: Tokens): string {
  const semantic = Object.entries(tokens.semantic).map(([name, token], index) => ({
    name: pascalCase(name),
    value: hexToComposeColor(token.value, COLOR_ALIAS),
    ...(index === 0
      ? { comment: "Semantic: fixed meanings (cash, UPI, pending, …), same as web." }
      : {}),
  }));
  const colors: Member[] = [
    ...Object.entries(tokens.color).map(([name, token]) => ({
      name: pascalCase(name),
      value: hexToComposeColor(token.value, COLOR_ALIAS),
    })),
    ...semantic,
  ];

  const fonts: Member[] = Object.entries(tokens.font.family).flatMap(([name, token]) => [
    {
      name: `${pascalCase(name)}Families`,
      value: `listOf(${token.value.map(kotlinString).join(", ")})`,
    },
    ...(token.features?.length
      ? [
          {
            name: `${pascalCase(name)}FeatureSettings`,
            value: kotlinString(composeFontFeatures(token.features)),
          },
        ]
      : []),
  ]);

  const weights: Member[] = Object.entries(tokens.font.weight).map(([name, token]) => ({
    name: pascalCase(name),
    value: `FontWeight(${token.value})`,
  }));

  const objects = [
    object("Color", colors),
    object("Font", fonts),
    object("Weight", weights),
    object("Type", lengths(tokens.type.android, sp)),
    object("Radius", lengths(tokens.radius, dp)),
    object("Border", lengths(tokens.border, dp)),
    object("Space", [
      {
        name: "Base",
        value: dp(tokens.space.base),
        comment: "Every spacing is a multiple of Base.",
      },
    ]),
    object(
      "Size",
      Object.entries(tokens.size).map(([name, size]) => ({
        name: pascalCase(name),
        value: dp(size.android),
      })),
    ),
    object("Elevation", lengths(tokens.elevation, dp)),
  ];

  const lines = [
    "// GENERATED by @cb/design-tokens (packages/design-tokens/scripts/build.ts). DO NOT EDIT.",
    "// Change packages/design-tokens/tokens.json, then run `pnpm tokens:build`.",
    '@file:Suppress("ktlint", "MagicNumber")',
    "",
    `package ${KOTLIN_PACKAGE}`,
    "",
    `import androidx.compose.ui.graphics.Color as ${COLOR_ALIAS}`,
    "import androidx.compose.ui.text.font.FontWeight",
    "import androidx.compose.ui.unit.dp",
    "import androidx.compose.ui.unit.sp",
    "",
    "/** Design tokens from packages/design-tokens/tokens.json (Android values). */",
    "object Tokens {",
    ...objects.flatMap((lines, index) => (index === 0 ? lines : ["", ...lines])),
    "}",
  ];
  return `${lines.join("\n")}\n`;
}
