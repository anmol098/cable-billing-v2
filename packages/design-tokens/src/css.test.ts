import { basename, dirname, join } from "node:path";
import { compile } from "@tailwindcss/node";
import { beforeAll, describe, expect, it } from "vitest";
import { renderThemeCss } from "./css";
import { loadTokens, REPO_ROOT } from "./fs";
import { OUTPUT_PATHS } from "./outputs";

const css = renderThemeCss(loadTokens());

describe("theme.css (string level)", () => {
  it("has the GENERATED header and imports Tailwind first", () => {
    expect(css.startsWith("/*\n * GENERATED by @cb/design-tokens")).toBe(true);
    expect(css).toContain('@import "tailwindcss";\n');
  });

  it("clears the default palette and shadows before adding tokens", () => {
    const reset = css.indexOf("--color-*: initial;");
    expect(reset).toBeGreaterThan(-1);
    expect(css).toContain("--shadow-*: initial;");
    expect(css.indexOf("--color-bg:")).toBeGreaterThan(reset);
  });

  it("exposes every token as a theme variable", () => {
    for (const line of [
      "--color-bg: #FFFFFF;",
      "--color-text-muted: #6B6B6B;",
      "--color-accent: #111111;",
      "--color-cash: #15803D;",
      '--font-sans: Inter, "Noto Sans Devanagari", system-ui, sans-serif;',
      '--font-numeric--font-feature-settings: "tnum";',
      "--font-weight-strong: 600;",
      "--text-base: 1rem;",
      "--text-amount: 2.25rem;",
      "--radius-md: 0.5rem;",
      "--spacing: 0.25rem;",
      "--spacing-touch-min: 2.75rem;",
      "--spacing-primary-button: 3rem;",
    ]) {
      expect(css).toContain(`  ${line}\n`);
    }
    expect(css).toContain("@utility border-hairline { border-width: 1px; }");
    expect(css).toContain("@utility border-strong { border-width: 2px; }");
  });
});

describe("theme.css compiled by Tailwind v4", () => {
  // Compile the COMMITTED file from packages/ui/src, so `@import "tailwindcss"` resolves the way
  // apps/web will resolve it (through @cb/ui's own tailwindcss dependency).
  const themePath = join(REPO_ROOT, OUTPUT_PATHS.css);
  type Build = (candidates: string[]) => string;
  let build: Build;
  /** Stock Tailwind, as a control: proves the "not generated" checks are not vacuous. */
  let buildDefault: Build;

  beforeAll(async () => {
    const compiler = await compile(`@import "./${basename(themePath)}";`, {
      base: dirname(themePath),
      onDependency: () => {},
    });
    build = (candidates) => compiler.build(candidates);
    const stock = await compile('@import "tailwindcss";', {
      base: import.meta.dirname,
      onDependency: () => {},
    });
    buildDefault = (candidates) => stock.build(candidates);
  });

  /** The CSS rule Tailwind generated for one utility class, or undefined. */
  function rule(candidate: string, compiler: Build = build): string | undefined {
    const out = compiler([candidate]);
    const selector = `.${candidate.replace(/[[\]:/.]/g, (c) => `\\${c}`)} {`;
    const start = out.indexOf(selector);
    if (start === -1) return undefined;
    return out.slice(start, out.indexOf("}", start) + 1);
  }

  it.each([
    ["bg-bg", "background-color: var(--color-bg)"],
    ["text-text", "color: var(--color-text)"],
    ["text-cash", "color: var(--color-cash)"],
    ["text-due", "color: var(--color-due)"],
    ["border-border", "border-color: var(--color-border)"],
    ["bg-accent", "background-color: var(--color-accent)"],
    ["rounded-md", "border-radius: var(--radius-md)"],
    ["border-hairline", "border-width: 1px"],
    ["border-b-hairline", "border-bottom-width: 1px"],
    ["border-strong", "border-width: 2px"],
    ["text-amount", "font-size: var(--text-amount)"],
    ["text-base", "font-size: var(--text-base)"],
    ["font-sans", "font-family: var(--font-sans)"],
    ["font-numeric", "font-feature-settings: var(--font-numeric--font-feature-settings)"],
    ["font-strong", "font-weight: var(--font-weight-strong)"],
    ["p-4", "padding: calc(var(--spacing) * 4)"],
    ["min-h-touch-min", "min-height: var(--spacing-touch-min)"],
    ["h-primary-button", "height: var(--spacing-primary-button)"],
  ])("generates %s", (candidate, declaration) => {
    expect(rule(candidate)).toContain(declaration);
  });

  it.each([
    "bg-red-500",
    "text-blue-600",
    "bg-white",
    "bg-black",
    "text-9xl",
    "text-xs",
    "rounded-3xl",
    "shadow",
    "shadow-md",
    "drop-shadow-lg",
    "font-mono",
    "font-bold",
  ])("does NOT generate the Tailwind default %s", (candidate) => {
    expect(rule(candidate, buildDefault), "stock Tailwind generates it").toBeDefined();
    expect(rule(candidate)).toBeUndefined();
  });

  it("emits token variables but none of the default palette", () => {
    const out = build(["bg-bg"]);
    expect(out).toContain("--color-cash: #15803D;");
    expect(out).toContain("--color-accent: #111111;");
    expect(out).not.toMatch(/--color-(red|blue|green|gray|slate|zinc|neutral)-\d/);
    expect(out).not.toMatch(/--shadow-/);
  });
});
