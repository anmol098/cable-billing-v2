-- Append-only guard for financial tables (PLAN §7.1). Use as
--   BEFORE UPDATE OR DELETE ... FOR EACH ROW EXECUTE FUNCTION app.forbid_update_delete('col', ...)
--   BEFORE TRUNCATE ... FOR EACH STATEMENT EXECUTE FUNCTION app.forbid_update_delete()
-- (generated by appendOnlyTriggerSql() in src/triggers). DELETE and TRUNCATE always fail; UPDATE
-- fails if a column outside the argument list changes. Messages name columns, never values.
CREATE OR REPLACE FUNCTION app.forbid_update_delete() RETURNS trigger
  LANGUAGE plpgsql
  SET search_path = pg_catalog
AS $$
DECLARE
  allowed text[] := coalesce(TG_ARGV, ARRAY[]::text[]);
  old_row jsonb;
  new_row jsonb;
  unknown_columns text[];
  changed_columns text[];
BEGIN
  IF TG_OP IN ('DELETE', 'TRUNCATE') THEN
    RAISE EXCEPTION '% on %.% is not allowed: the table is append-only', TG_OP, TG_TABLE_SCHEMA, TG_TABLE_NAME
      USING ERRCODE = 'CB001', HINT = 'Record a reversal or an adjustment instead.';
  END IF;
  IF TG_OP <> 'UPDATE' OR TG_LEVEL <> 'ROW' OR TG_WHEN <> 'BEFORE' THEN
    RAISE EXCEPTION 'app.forbid_update_delete() must run BEFORE UPDATE OR DELETE FOR EACH ROW (or BEFORE TRUNCATE)';
  END IF;

  old_row := to_jsonb(OLD);
  new_row := to_jsonb(NEW);

  SELECT array_agg(a ORDER BY a) INTO unknown_columns
    FROM unnest(allowed) AS a
   WHERE NOT old_row ? a;
  IF unknown_columns IS NOT NULL THEN
    RAISE EXCEPTION 'app.forbid_update_delete() on %.%: unknown column(s) %', TG_TABLE_SCHEMA, TG_TABLE_NAME, unknown_columns
      USING ERRCODE = 'undefined_column';
  END IF;

  SELECT array_agg(o.key ORDER BY o.key) INTO changed_columns
    FROM jsonb_each(old_row) AS o(key, value)
   WHERE NOT (o.key = ANY (allowed))
     AND (new_row -> o.key) IS DISTINCT FROM o.value;
  IF changed_columns IS NOT NULL THEN
    RAISE EXCEPTION 'UPDATE of % on %.% is not allowed: the table is append-only', changed_columns, TG_TABLE_SCHEMA, TG_TABLE_NAME
      USING ERRCODE = 'CB001', HINT = 'Record a reversal or an adjustment instead.';
  END IF;

  RETURN NEW;
END
$$;
