-- T-020 foundation: roles, the `app` schema, RLS helper and append-only trigger function.
-- Conventions and the security model: packages/db/README.md. Runs as the owner/migration role.
--
-- Roles are cluster-wide, so they are created only if missing (several databases on one server,
-- e.g. test databases or Neon branches, share them). Their attributes are verified by the
-- @cb/db test suite (no LOGIN, no BYPASSRLS, own nothing).
CREATE EXTENSION IF NOT EXISTS btree_gist;
--> statement-breakpoint
DO $$
BEGIN
  IF NOT EXISTS (SELECT FROM pg_catalog.pg_roles WHERE rolname = 'app_rw') THEN
    CREATE ROLE app_rw NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION NOBYPASSRLS;
  END IF;
  IF NOT EXISTS (SELECT FROM pg_catalog.pg_roles WHERE rolname = 'app_platform') THEN
    CREATE ROLE app_platform NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION NOBYPASSRLS;
  END IF;
  -- The role that connects at runtime switches to these with SET LOCAL ROLE inside every
  -- transaction, so it must be a member. Here that is the migration role itself (on Neon the
  -- database owner, which got ADMIN OPTION on the roles by creating them; a superuser needs nothing).
  IF NOT pg_catalog.pg_has_role(current_user, 'app_rw', 'MEMBER') THEN
    EXECUTE format('GRANT app_rw TO %I', current_user);
  END IF;
  IF NOT pg_catalog.pg_has_role(current_user, 'app_platform', 'MEMBER') THEN
    EXECUTE format('GRANT app_platform TO %I', current_user);
  END IF;
END
$$;
