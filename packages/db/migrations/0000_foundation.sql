-- The current tenant: `app.operator_id` set transaction-locally by withTenant, or NULL when unset.
-- After a transaction-local set_config ends, the setting reads as '' (not NULL) for the rest of
-- the session, hence nullif. NULL never equals an operator_id, so policies return no rows rather
-- than raising. Plain SQL + STABLE so the planner can inline it into policies and index scans.
CREATE OR REPLACE FUNCTION app.current_operator() RETURNS uuid
  LANGUAGE sql
  STABLE
  PARALLEL SAFE
AS $$
  SELECT nullif(pg_catalog.current_setting('app.operator_id', true), '')::uuid
$$;
--> statement-breakpoint
GRANT EXECUTE ON FUNCTION app.current_operator() TO app_rw, app_platform;
