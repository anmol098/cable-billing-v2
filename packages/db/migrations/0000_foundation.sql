-- Every table/sequence later migrations create (as this same role) in `public` is usable by the
-- app roles. RLS decides which rows: tenant tables have a policy for app_rw only, so app_platform
-- sees none of their rows. No TRUNCATE, REFERENCES or TRIGGER.
ALTER DEFAULT PRIVILEGES IN SCHEMA public
  GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO app_rw, app_platform;
--> statement-breakpoint
ALTER DEFAULT PRIVILEGES IN SCHEMA public
  GRANT USAGE, SELECT ON SEQUENCES TO app_rw, app_platform;
