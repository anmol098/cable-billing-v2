/**
 * Customers (T-022, PLAN §7.2, FR-003, FR-004, BR-01, RULE-02) and the history of their contact
 * numbers.
 *
 * **Customer code** (PLAN §7.3): operator-defined or auto (`nextCounter(tx, op, "customer_code")`),
 * unique **within one operator only** (PRD §15 #2): `UNIQUE (operator_id, customer_code_norm)`.
 * `customer_code_norm` is a stored generated column, so no write path (web, import, migration) can
 * skip the normalisation. {@link normalizeCustomerCode} is the same function in TypeScript, for
 * look-ups ("a 101" finds "A 101") and friendly duplicate errors before the insert:
 * 1. every run of ASCII whitespace (space, tab, CR, LF, FF, VT) becomes one space;
 * 2. a leading/trailing space is removed (trim);
 * 3. ASCII `a`–`z` become upper case. Nothing else changes: digits, leading zeros, punctuation and
 *    non-ASCII letters (e.g. Devanagari) are kept as typed, so "0101" and "101" stay different.
 * Upper-casing is ASCII-only on purpose: SQL `upper()` depends on the database locale, and a
 * generated column must give the same value on every server (CI, local, Neon).
 *
 * **Search** (T-033, the lineman app): `customers_name_trgm_idx` (GIN trigram, pg_trgm) for
 * `name % $q`, `similarity()` and `ILIKE '%…%'`; btree `text_pattern_ops` indexes on
 * `(operator_id, customer_code_norm)`, `(operator_id, phone)` and `(operator_id, alt_phone)` for
 * equality and prefix (`LIKE 'q%'`) look-ups. VC numbers are searched through `vc_assets`.
 *
 * **Phones** are stored as digits with an optional leading `+` (6–19 digits, like the operator's
 * office phone): services strip spaces/dashes before saving. Every change of `phone`/`alt_phone`
 * is recorded in `customer_contact_changes` by the service that makes it (FR-004).
 *
 * Customers are deactivated (`status = 'inactive'`), never deleted; their id and tenant never
 * change (triggers in the custom migration).
 */
import { sql } from "drizzle-orm";
import {
  check,
  foreignKey,
  index,
  jsonb,
  pgEnum,
  pgTable,
  text,
  timestamp,
  unique,
  uniqueIndex,
  uuid,
} from "drizzle-orm/pg-core";
import { primaryId } from "../ids";
import { operatorIdColumn, tenantKey, tenantPolicies } from "../rls";
import { users } from "./auth";
import { areas, operators } from "./tenancy";

export const CUSTOMER_STATUSES = ["active", "inactive"] as const;
export type CustomerStatus = (typeof CUSTOMER_STATUSES)[number];
export const customerStatusEnum = pgEnum("customer_status", CUSTOMER_STATUSES);

/** Which contact number changed (FR-004). */
export const CONTACT_FIELDS = ["phone", "alt_phone"] as const;
export type ContactField = (typeof CONTACT_FIELDS)[number];
export const contactFieldEnum = pgEnum("contact_field", CONTACT_FIELDS);

/** Where a contact change came from (FR-004 "source"). */
export const CONTACT_CHANGE_SOURCES = ["web", "android", "import"] as const;
export type ContactChangeSource = (typeof CONTACT_CHANGE_SOURCES)[number];
export const contactChangeSourceEnum = pgEnum("contact_change_source", CONTACT_CHANGE_SOURCES);

/** Longest normalised customer code / VC number accepted. */
export const MAX_CODE_LENGTH = 64;

const LOWER = "abcdefghijklmnopqrstuvwxyz";
const UPPER = "ABCDEFGHIJKLMNOPQRSTUVWXYZ";
/** SQL `translate(...)` arguments for ASCII-only upper-casing (locale independent). */
export const SQL_ASCII_UPPER_ARGS = `'${LOWER}', '${UPPER}'`;

/** ASCII upper case for a-z only (the TypeScript side of `translate(x, 'a…z', 'A…Z')`). */
export function asciiUpper(value: string): string {
  return value.replace(/[a-z]/g, (c) => c.toUpperCase());
}

/**
 * The customer code as the database stores it in `customer_code_norm` (see the module comment).
 * Kept identical to the generated column's expression; `customers.test.ts` checks both agree.
 */
export function normalizeCustomerCode(code: string): string {
  return asciiUpper(code.replace(/[ \t\n\r\f\v]+/g, " ").replace(/^ | $/g, ""));
}

/** Contact numbers: digits with an optional leading `+`, 6–19 digits. */
export const PHONE_PATTERN = "^\\+?[0-9]{6,19}$";

export const customers = pgTable(
  "customers",
  {
    id: primaryId(),
    operatorId: operatorIdColumn().references(() => operators.id),
    /** As entered (shown to users). */
    customerCode: text("customer_code").notNull(),
    /** {@link normalizeCustomerCode}(customer_code), generated by the database. */
    customerCodeNorm: text("customer_code_norm")
      .notNull()
      .generatedAlwaysAs(
        sql.raw(
          `translate(btrim(regexp_replace("customer_code", '[ \\t\\n\\r\\f\\v]+', ' ', 'g'), ' '), ${SQL_ASCII_UPPER_ARGS})`,
        ),
      ),
    name: text("name").notNull(),
    /** Main mobile number (WhatsApp/SMS receipts are prepared for it after confirmation, FR-004). */
    phone: text("phone"),
    altPhone: text("alt_phone"),
    address: text("address"),
    /** NULL when the area is unknown (e.g. legacy rows without one). */
    areaId: uuid("area_id"),
    status: customerStatusEnum("status").notNull().default("active"),
    /**
     * Available KYC metadata (FR-003), a JSON object. Personal data: keep it out of logs and
     * redact it in audit `before`/`after` (FR-024).
     */
    kyc: jsonb("kyc").$type<Record<string, unknown>>().notNull().default({}),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
    legacySource: text("legacy_source"),
    legacyId: text("legacy_id"),
  },
  (t) => [
    tenantKey(t),
    unique("customers_operator_code_unique").on(t.operatorId, t.customerCodeNorm),
    uniqueIndex("customers_operator_legacy_unique")
      .on(t.operatorId, t.legacySource, t.legacyId)
      .where(sql`${t.legacyId} IS NOT NULL`),
    foreignKey({
      name: "customers_area_fk",
      columns: [t.operatorId, t.areaId],
      foreignColumns: [areas.operatorId, areas.id],
    }),
    // Search (T-033).
    index("customers_name_trgm_idx").using("gin", t.name.op("gin_trgm_ops")),
    index("customers_code_prefix_idx").on(t.operatorId, t.customerCodeNorm.op("text_pattern_ops")),
    index("customers_phone_idx").on(t.operatorId, t.phone.op("text_pattern_ops")),
    index("customers_alt_phone_idx").on(t.operatorId, t.altPhone.op("text_pattern_ops")),
    index("customers_area_idx").on(t.operatorId, t.areaId),
    check(
      "customers_code_valid",
      sql`${t.customerCodeNorm} <> '' AND char_length(${t.customerCodeNorm}) <= ${sql.raw(String(MAX_CODE_LENGTH))}`,
    ),
    check("customers_name_not_blank", sql`btrim(${t.name}) <> ''`),
    check("customers_phone_format", sql`${t.phone} ~ ${sql.raw(`'${PHONE_PATTERN}'`)}`),
    check("customers_alt_phone_format", sql`${t.altPhone} ~ ${sql.raw(`'${PHONE_PATTERN}'`)}`),
    check("customers_kyc_object", sql`jsonb_typeof(${t.kyc}) = 'object'`),
    check(
      "customers_legacy_both_or_neither",
      sql`(${t.legacySource} IS NULL) = (${t.legacyId} IS NULL)`,
    ),
    ...tenantPolicies(t),
  ],
).enableRLS();

/**
 * FR-004: every change of a customer's contact number, with old/new value, actor, time and source.
 * Append-only for every role (trigger in the custom migration). `actor_id` is required except for
 * `import` rows written by a system process.
 */
export const customerContactChanges = pgTable(
  "customer_contact_changes",
  {
    id: primaryId(),
    operatorId: operatorIdColumn(),
    customerId: uuid("customer_id").notNull(),
    field: contactFieldEnum("field").notNull(),
    /** NULL: there was no number before. */
    oldValue: text("old_value"),
    /** NULL: the number was removed. */
    newValue: text("new_value"),
    actorId: uuid("actor_id"),
    source: contactChangeSourceEnum("source").notNull(),
    at: timestamp("at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [
    tenantKey(t),
    foreignKey({
      name: "customer_contact_changes_customer_fk",
      columns: [t.operatorId, t.customerId],
      foreignColumns: [customers.operatorId, customers.id],
    }),
    foreignKey({
      name: "customer_contact_changes_actor_fk",
      columns: [t.operatorId, t.actorId],
      foreignColumns: [users.operatorId, users.id],
    }),
    index("customer_contact_changes_customer_idx").on(t.operatorId, t.customerId, t.at),
    check("customer_contact_changes_changed", sql`${t.oldValue} IS DISTINCT FROM ${t.newValue}`),
    check(
      "customer_contact_changes_actor_required",
      sql`${t.source} = 'import' OR ${t.actorId} IS NOT NULL`,
    ),
    ...tenantPolicies(t),
  ],
).enableRLS();
